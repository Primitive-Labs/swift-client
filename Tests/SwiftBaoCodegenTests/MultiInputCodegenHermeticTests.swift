import Foundation
import XCTest
@testable import swift_bao_codegen

/// `swift-bao-codegen` over several schema files (#5025 behaviours 9 and 10,
/// edges E4 and E5).
///
/// An app whose clients open more than one kind of db3 generates its structs
/// from every type file in one run: one struct per model over the union, one
/// `GeneratedModels.swift` naming them all, each model file's header naming
/// the file that declared it and the barrel's naming every input. A model two
/// files declare must be declared the same way in both.
///
/// Hermetic: `CodegenInputs` over temporary directories and `CodegenRun` over
/// in-memory documents, the two halves `main.swift` runs.
final class MultiInputCodegenHermeticTests: XCTestCase {

    private static let accounts = """
        [type]
        name = "a"

        [models.accounts]
        class_name = "Account"

        [models.accounts.fields.id]
        type = "id"
        auto_assign = true

        [models.accounts.fields.name]
        type = "string"
        """

    private static let holdings = """
        [type]
        name = "b"

        [models.holdings]
        class_name = "Holding"

        [models.holdings.fields.id]
        type = "id"
        auto_assign = true

        [models.holdings.fields.account_id]
        type = "string"
        indexed = true

        [models.holdings.relationships.account]
        type = "refersTo"
        model = "accounts"
        related_id_field = "account_id"
        """

    private func render(_ documents: [(String, String)], emptyLabel: String = "") throws -> [String: String] {
        let files = try CodegenRun.render(
            documents: documents.map { (sourceName: $0.0, source: $0.1) },
            emptyLabel: emptyLabel,
            accessLevel: "public",
            moduleImport: "JsBaoClient",
            swiftNameSuffix: "Record",
            strict: true
        )
        return Dictionary(uniqueKeysWithValues: files.map { ($0.fileName, $0.source) })
    }

    private func failure(_ documents: [(String, String)], file: StaticString = #filePath, line: UInt = #line) -> String {
        do {
            let files = try render(documents)
            XCTFail("expected a refusal, got \(files.keys.sorted())", file: file, line: line)
            return ""
        } catch let error as CodegenError {
            return error.description
        } catch {
            XCTFail("expected a CodegenError, got \(error)", file: file, line: line)
            return ""
        }
    }

    private func sandbox() throws -> URL {
        let root = URL(fileURLWithPath: NSTemporaryDirectory()).appending(path: "swift-bao-5025-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: root) }
        return root
    }

    private func put(_ text: String, at url: URL) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try text.write(to: url, atomically: true, encoding: .utf8)
    }

    // MARK: - Behaviour 9

    func testTwoInputsEmitOneStructPerModelAndOneBarrelNamingBoth() throws {
        let files = try render([("a.toml", Self.accounts), ("b.toml", Self.holdings)])
        XCTAssertEqual(files.keys.sorted(), ["Account.swift", "GeneratedModels.swift", "Holding.swift"])
        XCTAssertTrue(files["Account.swift"]!.hasPrefix(
            "// Generated by swift-bao-codegen — DO NOT EDIT.\n// Source: a.toml (model: accounts)\n"))
        XCTAssertTrue(files["Holding.swift"]!.hasPrefix(
            "// Generated by swift-bao-codegen — DO NOT EDIT.\n// Source: b.toml (model: holdings)\n"))
        let barrel = files["GeneratedModels.swift"]!
        XCTAssertTrue(barrel.contains("// Source: a.toml, b.toml (registration barrel)\n"))
        XCTAssertTrue(barrel.contains("        Account.self,\n        Holding.self,\n    ]"))
        XCTAssertTrue(barrel.contains("        \"accounts\",\n        \"holdings\",\n    ]"))
        // The relationship in b.toml names the model a.toml declares.
        XCTAssertTrue(files["Holding.swift"]!.contains("public func account() throws -> Account? {"))
    }

    func testADirectoryContributesItsTomlFilesInNameOrderOnce() throws {
        let root = try sandbox()
        let dir = root.appending(path: "db3-types")
        try put(Self.holdings, at: dir.appending(path: "b.toml"))
        try put(Self.accounts, at: dir.appending(path: "a.toml"))
        try put(Self.accounts, at: dir.appending(path: "nested/c.toml"))
        try put("not a schema", at: dir.appending(path: "notes.txt"))
        let a = dir.appending(path: "a.toml").path(percentEncoded: false)
        let b = dir.appending(path: "b.toml").path(percentEncoded: false)

        let expanded = try CodegenInputs.expand([dir.path(percentEncoded: false)])
        XCTAssertEqual(expanded.map { URL(fileURLWithPath: $0).lastPathComponent }, ["a.toml", "b.toml"])
        XCTAssertEqual(try CodegenInputs.expand([a, dir.path(percentEncoded: false), a]).count, 2)
        XCTAssertEqual(try CodegenInputs.expand([b, a]).map { URL(fileURLWithPath: $0).lastPathComponent }, ["b.toml", "a.toml"])

        let documents = try CodegenInputs.read(expanded)
        XCTAssertEqual(documents.map(\.sourceName), ["a.toml", "b.toml"])
        let fromDirectory = try render(documents.map { ($0.sourceName, $0.source) })
        XCTAssertEqual(fromDirectory, try render([("a.toml", Self.accounts), ("b.toml", Self.holdings)]))
    }

    // MARK: - Behaviour 10

    func testAModelDeclaredTheSameWayTwiceIsOneStructFromTheFirstFile() throws {
        let again = Self.accounts.replacingOccurrences(of: "name = \"a\"", with: "name = \"c\"")
        let files = try render([("a.toml", Self.accounts), ("c.toml", again)])
        XCTAssertEqual(files.keys.sorted(), ["Account.swift", "GeneratedModels.swift"])
        XCTAssertTrue(files["Account.swift"]!.contains("// Source: a.toml (model: accounts)\n"))
        XCTAssertEqual(files["GeneratedModels.swift"]!.components(separatedBy: "Account.self").count, 2)
    }

    func testAModelDeclaredDifferentlyIsRefusedNamingBothFilesAndTheFields() {
        let differing = Self.accounts
            .replacingOccurrences(of: "name = \"a\"", with: "name = \"c\"")
            .replacingOccurrences(of: "[models.accounts.fields.name]\ntype = \"string\"",
                                  with: "[models.accounts.fields.name]\ntype = \"string\"\nrequired = true\n\n[models.accounts.fields.email]\ntype = \"string\"")
        let message = failure([("a.toml", Self.accounts), ("c.toml", differing)])
        XCTAssertTrue(message.contains("`accounts`"), message)
        XCTAssertTrue(message.contains("a.toml"), message)
        XCTAssertTrue(message.contains("c.toml"), message)
        XCTAssertTrue(message.contains("field `email` is only in c.toml"), message)
        XCTAssertTrue(message.contains("field `name` differs"), message)
    }

    func testASwiftNameCollisionAcrossFilesIsRefusedAsToday() {
        let other = """
            [models.ledgers]
            class_name = "Account"

            [models.ledgers.fields.id]
            type = "id"
            """
        let message = failure([("a.toml", Self.accounts), ("b.toml", other)])
        XCTAssertTrue(message.contains("Account.swift would be written by multiple models: accounts, ledgers"), message)
    }

    // MARK: - E4, E5

    func testTwoFilesWithOneBasenameAreNamedByBasenameAndShareAnIdenticalModel() throws {
        let files = try render([("schema.toml", Self.accounts), ("schema.toml", Self.accounts)])
        XCTAssertEqual(files.keys.sorted(), ["Account.swift", "GeneratedModels.swift"])
        XCTAssertTrue(files["GeneratedModels.swift"]!.contains("// Source: schema.toml, schema.toml (registration barrel)\n"))
        XCTAssertTrue(files["Account.swift"]!.contains("// Source: schema.toml (model: accounts)\n"))
    }

    func testADirectoryWithNoTomlEmitsTheEmptyBarrel() throws {
        let root = try sandbox()
        let dir = root.appending(path: "db3-types")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        XCTAssertEqual(try CodegenInputs.expand([dir.path(percentEncoded: false)]), [])

        let files = try render([], emptyLabel: "db3-types/")
        XCTAssertEqual(files.keys.sorted(), ["GeneratedModels.swift"])
        let empty = try render([("schema.toml", "")])
        XCTAssertEqual(
            files["GeneratedModels.swift"],
            empty["GeneratedModels.swift"]!.replacingOccurrences(of: "// Source: schema.toml", with: "// Source: db3-types/"))
    }

    // MARK: - One input, as before

    func testOneInputRendersTheCommittedGolden() throws {
        let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        let source = try String(
            contentsOf: root.appending(path: "Tests/JsBaoClientTests/CrossPlatform/harness/fixtures/sample-schema.toml"),
            encoding: .utf8)
        let goldens = root.appending(path: "Tests/SwiftBaoCodegenTests/Goldens/sample-schema")
        var committed: [String: String] = [:]
        for name in try FileManager.default.contentsOfDirectory(atPath: goldens.path(percentEncoded: false))
        where name.hasSuffix(".golden") {
            committed[String(name.dropLast(".golden".count))] = try String(
                contentsOf: goldens.appending(path: name), encoding: .utf8)
        }
        XCTAssertEqual(try render([("sample-schema.toml", source)]), committed)
    }
}
